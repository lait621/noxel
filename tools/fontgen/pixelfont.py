def _parse() -> dict[str, list[str]]:
    """Turns the art table into `{character: [row, row, ...]}`.

    Raises `ValueError` on a malformed row, which is the one failure mode worth
    making loud: a row of the wrong width silently shifts every glyph after it.
    """
    glyphs: dict[str, list[str]] = {}
    for line in _ART.splitlines():
        if len(line) < 2:
            raise ValueError(f"art line is too short to hold a key: {line!r}")
        key, cell = line[0], line[2:]
        if not cell:
            raise ValueError(f"glyph {key!r} has no art")
        rows = cell.split("/")
        if len(rows) != HEIGHT:
            raise ValueError(f"glyph {key!r} has {len(rows)} rows, expected {HEIGHT}")
        for index, row in enumerate(rows):
            if len(row) != WIDTH:
                raise ValueError(
                    f"glyph {key!r} row {index} is {len(row)} wide, expected {WIDTH}: {row!r}"
                )
            if set(row) - {"#", "."}:
                raise ValueError(f"glyph {key!r} row {index} uses a character other than # or .")
        if key in glyphs:
            raise ValueError(f"glyph {key!r} is defined twice")
        glyphs[key] = rows
    return glyphs


#: Every glyph, keyed by the single character it draws.
GLYPHS: dict[str, list[str]] = _parse()


def ink_bounds(rows: list[str]) -> tuple[int, int] | None:
    """The inclusive `(first, last)` ink column, or `None` for a blank glyph."""
    columns = [x for x in range(WIDTH) if any(row[x] == "#" for row in rows)]
    if not columns:
        return None
    return columns[0], columns[-1]



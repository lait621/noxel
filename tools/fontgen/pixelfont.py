"""The hand-authored 5x7 pixel font used by Noxel's UI layer.

This module is the **source of truth** for the Latin glyphs. It is deliberately
plain data: a contributor adds a character by drawing it, and `fontgen.py`
turns the drawing into an atlas. Nothing here rasterises anything, so the font
is exactly as crisp as the grid it is drawn on — every stroke lands on a whole
pixel at 1x, and every integer upscale of it stays sharp (`Image`/`Texture`
sampling in the engine is nearest-neighbour for pixel art).

Grid
----

Each glyph is a list of 9 rows of 5 columns, in reading order:

```text
row 0   cap top          \
row 1                     |
row 2   x-height top      |  7 rows: cap height, and ascenders (b d f h k l)
row 3                     |  5 rows: x-height (a c e m n o r s u v w x z)
row 4                     |
row 5                     |
row 6   baseline         /
row 7   descender        \
row 8   descender        /   (g j p q y , ;)
```

The baseline is row 6, which is what makes a descender possible at all: a font
whose baseline is the last row cannot draw `g` without moving every other
glyph up. `fontgen.py` stores the baseline in the atlas metadata rather than
baking it into the bitmaps, so a line of mixed text can align two faces of
different heights on one baseline.

Drawing conventions
-------------------

`#` is ink, `.` is empty, and every row is exactly 5 characters. Rows are joined
with `/` in the `GLYPHS` table below so that one glyph is one line of Python and
a diff shows exactly which character changed.
"""

